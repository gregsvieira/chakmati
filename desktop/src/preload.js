'use strict';
// The only bridge between the windows and the app. The windows have no Node and no network; they can call exactly these
// functions, and each one is validated again in the main process.
const { contextBridge, ipcRenderer } = require('electron');

const listen = (channel, cb) => {
  const handler = (_event, payload) => cb(payload);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
};
const send = (channel, payload) => ipcRenderer.send(channel, payload);

contextBridge.exposeInMainWorld('assistant', {
  voice: { synthesize: (text, speed) => ipcRenderer.invoke('voice:synthesize', text, speed) },
  installer: {
    scan: () => ipcRenderer.invoke('installer:scan'),
    plan: (selected, profile, opts) => ipcRenderer.invoke('installer:plan', selected, profile, opts),
    run: (selected, profile, opts) => ipcRenderer.invoke('installer:run', selected, profile, opts),
    cloudCheck: (provider, key, model) => ipcRenderer.invoke('installer:cloud-check', typeof provider === 'string' ? provider : '', typeof key === 'string' ? key : '', typeof model === 'string' ? model : ''),
    cloudClear: () => ipcRenderer.invoke('installer:cloud-clear'),
    ollamaPage: () => ipcRenderer.invoke('installer:ollama-page'),
    onProgress: (cb) => listen('installer:progress', cb),
    finish: () => send('installer:finish'),
    homePrepare: () => ipcRenderer.invoke('installer:home-prepare'),
    homeDiscover: () => ipcRenderer.invoke('panel:home-discover'),
    homeConnect: (url) => ipcRenderer.invoke('panel:home-connect', typeof url === 'string' ? url : ''),
    homeStatus: () => ipcRenderer.invoke('panel:home-status'),
    homeInstallInfo: () => ipcRenderer.invoke('panel:home-install-info'),
    homeInstallStart: () => ipcRenderer.invoke('panel:home-install-start'),
    homeAccount: (name, password) => ipcRenderer.invoke('panel:home-account', typeof name === 'string' ? name : '', typeof password === 'string' ? password : ''),
    homeAlexaStart: (region, email, password) => ipcRenderer.invoke('panel:home-alexa-start', typeof region === 'string' ? region : '', typeof email === 'string' ? email : '', typeof password === 'string' ? password : ''),
    homeAlexaStatus: () => ipcRenderer.invoke('panel:home-alexa-status'),
    homeAlexaCancel: () => ipcRenderer.invoke('panel:home-alexa-cancel'),
    homeOpenHa: () => ipcRenderer.invoke('panel:home-open-ha'),
  },
  widget: {
    onLayout: (cb) => listen('widget:layout', cb),
    onBubble: (cb) => listen('widget:bubble', cb),
    onMood: (cb) => listen('widget:mood', cb),
    onListening: (cb) => listen('widget:listening', cb),
    onBell: (cb) => listen('widget:bell', cb),
    onVoice: (cb) => listen('widget:voice', cb),
    onStill: (cb) => listen('widget:still', cb),
    onBackdrop: (cb) => listen('widget:backdrop', cb),
    ready: () => send('widget:ready'),
    hover: (inside) => send('widget:hover', !!inside),
    speaking: (on) => send('widget:speaking', !!on),
    dragStart: () => send('widget:drag-start'),
    dragMove: (dx, dy) => send('widget:drag-move', { dx, dy }),
    dragEnd: (moved) => send('widget:drag-end', !!moved),
    toggle: () => send('widget:toggle'),
    bubbleClick: () => send('widget:bubble-click'),
    menu: () => send('widget:menu'),
  },
  panel: {
    onState: (cb) => listen('panel:state', cb),
    onOtherSpeaking: (cb) => listen('panel:other-speaking', cb),
    onMessage: (cb) => listen('panel:message', cb),
    ready: () => send('panel:ready'),
    close: () => send('panel:close'),
    openLink: (url) => send('panel:open-link', String(url).slice(0, 2000)),
    setLayout: (mode) => send('panel:layout', mode),
    removeVoice: () => ipcRenderer.invoke('panel:voice-remove'),
    reply: (text) => send('panel:reply', { text }),
    refresh: () => send('panel:refresh'),
    panic: () => send('panel:panic'),
    restart: () => send('panel:restart'),
    openWa: () => ipcRenderer.invoke('panel:openwa'),
    homeDiscover: () => ipcRenderer.invoke('panel:home-discover'),
    homeConnect: (url) => ipcRenderer.invoke('panel:home-connect', typeof url === 'string' ? url : ''),
    homeStatus: () => ipcRenderer.invoke('panel:home-status'),
    homeInstallInfo: () => ipcRenderer.invoke('panel:home-install-info'),
    homeInstallStart: () => ipcRenderer.invoke('panel:home-install-start'),
    homeAccount: (name, password) => ipcRenderer.invoke('panel:home-account', typeof name === 'string' ? name : '', typeof password === 'string' ? password : ''),
    homeAlexaStart: (region, email, password) => ipcRenderer.invoke('panel:home-alexa-start', typeof region === 'string' ? region : '', typeof email === 'string' ? email : '', typeof password === 'string' ? password : ''),
    homeAlexaStatus: () => ipcRenderer.invoke('panel:home-alexa-status'),
    homeAlexaCancel: () => ipcRenderer.invoke('panel:home-alexa-cancel'),
    cloudProviders: () => ipcRenderer.invoke('panel:cloud-providers'),
    cloudSave: (provider, key, model, local) => ipcRenderer.invoke('panel:cloud-save', typeof provider === 'string' ? provider : '', typeof key === 'string' ? key : '', typeof model === 'string' ? model : '', local !== false),
    cloudRemove: () => ipcRenderer.invoke('panel:cloud-remove'),
    homeOpenHa: () => ipcRenderer.invoke('panel:home-open-ha'),
    homeDisconnect: () => ipcRenderer.invoke('panel:home-disconnect'),
    chats: () => ipcRenderer.invoke('panel:chats'),
    messages: (chatId) => ipcRenderer.invoke('panel:messages', chatId),
    audio: (chatId, messageId) => ipcRenderer.invoke('panel:audio', chatId, messageId),
    transcribe: (bytes, mime) => ipcRenderer.invoke('panel:transcribe', bytes, mime),
    send: (text) => ipcRenderer.invoke('panel:send', text),
    answerInput: (jobId, requestId, value) => ipcRenderer.invoke('panel:input', jobId, requestId, value),
    cancel: (id) => send('panel:cancel', id),
    automation: (id, op) => ipcRenderer.invoke('panel:automation', id, op),
    preview: (id) => ipcRenderer.invoke('panel:preview', id),
    proposeRecorded: (bytes) => ipcRenderer.invoke('panel:propose-recorded', bytes),
    live: (text) => send('panel:live', text),
    approve: (id) => ipcRenderer.invoke('panel:approve', id),
    reject: (id) => ipcRenderer.invoke('panel:reject', id),
    setSetting: (key, value) => ipcRenderer.invoke('panel:set-setting', { key, value }),
  },
});
